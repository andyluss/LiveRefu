import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { loadVault } from '../../../design/projects/livedso/src/vault.ts'
import { resolveSkinColor } from '../../../design/projects/livedso/src/skin.ts'
import { THEMES, VARIANTS } from '../server/themes.ts'

const ROOT = resolve(import.meta.dirname, '..')
const LIVEDSO = resolve(ROOT, '../../design/projects/livedso')
const OUT_CSS = join(ROOT, 'web/themes.generated.css')
const OUT_JS = join(ROOT, 'web/themes.generated.js')
const CHECK = process.argv.includes('--check')
const LIST = process.argv.includes('--list')

function hex(c: { r: number; g: number; b: number }): string {
  return '#' + [c.r, c.g, c.b].map(v => Math.round(v).toString(16).padStart(2, '0')).join('').toUpperCase()
}
function color(vault: ReturnType<typeof loadVault>, path: string | undefined): string {
  if (!path) return ''
  const c = resolveSkinColor(vault, path)
  return c ? hex(c) : ''
}
function generate(): string {
  const lines = [
    '/* AUTO-GENERATED by products/manmanji/tools/build-themes.ts — DO NOT EDIT.',
    ' * Source: LiveDSO vaults/<id>/style-cards/<card>.json',
    ' * Run: npm run themes',
    ' */'
  ]
  for (const theme of VARIANTS) {
    if (!theme.vault || !theme.card) continue
    const vault = loadVault(join(LIVEDSO, 'vaults', theme.vault))
    const card = vault.styleCards.find(c => c.id === theme.card)
    if (!card) throw new Error(`找不到风格卡 ${theme.vault}/${theme.card}`)
    const roles = card.roles || {}
    const pick = (name: string, fallback: string) => color(vault, roles[name]) || fallback
    const bg = pick('bg', '#F4EEDF')
    const surface = pick('surface', bg)
    const raised = pick('surfaceRaised', surface)
    const text = pick('text', '#1B2A2F')
    const muted = pick('textMuted', text)
    const border = pick('border', muted)
    const borderStrong = pick('borderStrong', border)
    const action = pick('action', text)
    const onAction = pick('onAction', bg)
    const actionHover = pick('actionHover', action)
    const focus = pick('focus', action)
    const danger = pick('danger', '#A83A14')
    const warning = pick('warning', '#8A5A00')
    const success = pick('success', '#2F6B3A')
    const vars: Record<string, string> = {
      '--mm-bg': bg,
      '--mm-bg-2': pick('surfaceSunken', bg),
      '--mm-surface': surface,
      '--mm-raised': raised,
      '--mm-paper': surface,
      '--mm-text': text,
      '--mm-muted': muted,
      '--mm-faint': pick('textSubtle', muted),
      '--mm-line': border,
      '--mm-line-strong': borderStrong,
      '--mm-action': action,
      '--mm-on-action': onAction,
      '--mm-action-hover': actionHover,
      '--mm-focus': focus,
      '--mm-danger': danger,
      '--mm-warning': warning,
      '--mm-success': success,
      '--mm-amber': warning,
      '--mm-rust': danger
    }
    lines.push('', `/* ${theme.name} · ${theme.vault}/${theme.card} */`, `[data-style="${theme.id}"] {`, `  color-scheme: ${theme.mode};`)
    for (const [k, v] of Object.entries(vars)) lines.push(`  ${k}: ${v};`)
    lines.push('}')
  }
  lines.push('')
  return lines.join('\n')
}
function js(): string {
  const list = THEMES.map(t => ({ id: t.id, name: t.name, light: t.light, dark: t.dark }))
  return `// AUTO-GENERATED by tools/build-themes.ts — DO NOT EDIT.\nexport const THEMES = ${JSON.stringify(list, null, 2)}\nexport const VARIANTS = ${JSON.stringify(VARIANTS.map(v => ({ id: v.id, name: v.name, mode: v.mode })), null, 2)}\n`
}
function write(path: string, content: string): boolean {
  if (CHECK) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== content) {
      console.error(`✗ 生成物过期：${path}`)
      return false
    }
    return true
  }
  writeFileSync(path, content)
  return true
}
if (LIST) { for (const t of THEMES) console.log(`${t.id}\t${t.name}\t${t.light} / ${t.dark}`) }
else {
  const ok = write(OUT_CSS, generate()) && write(OUT_JS, js())
  if (CHECK) { if (ok) console.log('✓ themes 生成物已是最新'); else process.exitCode = 1 }
  else console.log(`themes → ${OUT_CSS}`)
}
