import type { Issue, LintResult, World } from './types.ts'

const VALID_CONFIDENCE = new Set(['canon', 'draft', 'rumor'])

export function lintWorld(world: World): LintResult {
  const issues: Issue[] = []
  const push = (issue: Issue): void => { issues.push(issue) }
  const eraIds = new Set(world.eras.map(e => e.id))
  const canonIds = new Set(world.canon.map(c => c.id))

  for (const era of world.eras) {
    if (!era.cost) push({ code: 'era.cost', severity: 'warn', path: era.id, message: `${era.name} 没有写“代价/谁承担”。` })
    if (!era.maintenance) push({ code: 'era.maintenance', severity: 'warn', path: era.id, message: `${era.name} 没有写“谁维护”。` })
    if (!era.style?.colors?.length) push({ code: 'era.style', severity: 'warn', path: era.id, message: `${era.name} 没有风格色板。` })
  }

  for (const fact of world.canon) {
    if (!eraIds.has(fact.era)) push({ code: 'canon.era', severity: 'error', path: fact.id, message: `canon 指向不存在的时代：${fact.era}` })
    if (!VALID_CONFIDENCE.has(fact.confidence)) push({ code: 'canon.confidence', severity: 'warn', path: fact.id, message: `confidence 非法：${fact.confidence}` })
    if (!fact.sources?.length) push({ code: 'canon.source', severity: 'warn', path: fact.id, message: `${fact.id} 没有来源。` })
    for (const dep of fact.dependsOn || []) {
      if (!canonIds.has(dep)) push({ code: 'canon.dependency', severity: 'error', path: fact.id, message: `${fact.id} 依赖不存在的 canon：${dep}` })
    }
    if ((fact.conflictsWith || []).length) {
      push({ code: 'canon.conflict', severity: 'error', path: fact.id, message: `${fact.id} 与 ${fact.conflictsWith.join('、')} 冲突。`, detail: fact.statement })
    }
  }

  for (const entity of world.entities) {
    if (!eraIds.has(entity.era)) push({ code: 'entity.era', severity: 'error', path: entity.id, message: `实体 ${entity.name} 指向不存在的时代：${entity.era}` })
  }

  for (const asset of world.assets) {
    if (!asset.source) push({ code: 'asset.source', severity: 'warn', path: asset.id, message: `${asset.title} 没有来源。` })
    if (!asset.license) push({ code: 'asset.license', severity: 'warn', path: asset.id, message: `${asset.title} 没有许可。` })
    if (!eraIds.has(asset.era)) push({ code: 'asset.era', severity: 'warn', path: asset.id, message: `${asset.title} 指向不存在的时代：${asset.era}` })
  }

  for (const output of world.outputs) {
    if (output.era !== 'all' && !eraIds.has(output.era)) push({ code: 'output.era', severity: 'warn', path: output.id, message: `${output.name} 指向不存在的时代：${output.era}` })
  }

  const errors = issues.filter(i => i.severity === 'error').length
  const warnings = issues.filter(i => i.severity === 'warn').length
  const infos = issues.filter(i => i.severity === 'info').length
  const score = Math.max(0, Math.min(100, 100 - errors * 14 - warnings * 4))
  return { issues, errors, warnings, infos, score }
}

export function worldBible(world: World): string {
  const eras = world.eras.map(e => `### ${e.name} · ${e.subtitle} (${e.from}–${e.to})\n\n- 技术：${e.tech}\n- 维护：${e.maintenance}\n- 代价：${e.cost}\n- 风格：${e.style.colors.join(' / ')}；${e.style.materials.join('、')}；${e.style.light}\n\n${e.summary}`).join('\n\n')
  const canon = world.canon.map(c => `- **${c.id}** (${c.era}, ${c.confidence}) — ${c.statement}\n  - 来源：${(c.sources || []).join('、') || '—'}\n  - 依赖：${(c.dependsOn || []).join('、') || '—'} ｜ 冲突：${(c.conflictsWith || []).join('、') || '—'}`).join('\n')
  const entities = world.entities.map(e => `- **${e.name}** \`${e.type}\` (${e.era}) — ${e.summary}`).join('\n')
  const assets = world.assets.map(a => `- **${a.title}** (${a.era}, ${a.type}) — source: ${a.source || '—'} ／ license: ${a.license || '—'} ／ ${a.status}`).join('\n')
  return `# ${world.title}\n\n> ${world.subtitle}\n\n${world.premise}\n\n## 约束\n\n${world.constraints.map(c => `- **${c.label}**：${c.statement}`).join('\n')}\n\n## 时代\n\n${eras}\n\n## Canon\n\n${canon}\n\n## 实体\n\n${entities}\n\n## 资产\n\n${assets}\n\n---\n\nGenerated by LiveLand. 本地生成，不替代人工审校。\n`
}

export function styleGuide(world: World): string {
  return `# ${world.title} · 风格指南\n\n${world.eras.map(e => `## ${e.name} · ${e.subtitle}\n\n- 技术：${e.tech}\n- 维护：${e.maintenance}\n- 代价：${e.cost}\n- 色板：${e.style.colors.join(' / ')}\n- 材料：${e.style.materials.join('、')}\n- 光照：${e.style.light}\n\n${e.summary}`).join('\n\n')}\n\n> 颜色/材料/光照只换皮肤；canon、信息位置、可读性不换。\n`
}

export function assetManifest(world: World): string {
  return JSON.stringify({
    world: world.id,
    version: world.version,
    assets: world.assets.map(a => ({ id: a.id, title: a.title, era: a.era, type: a.type, source: a.source, license: a.license, status: a.status, path: a.path }))
  }, null, 2) + '\n'
}
